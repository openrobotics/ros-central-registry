"""Generates a lazily-forwarding shim for a ROCm shared library.

The shim has the real library's SONAME and exports its symbols, so programs
link against it as against the real library. Each exported function is an
assembly trampoline that, on its first call, loads the real library (from
ROCM_PATH, /opt/rocm or the default search path) and from then on jumps
straight to the real function. Without the real library (no ROCm installed),
a function returns the library's error code instead (or with --abort,
aborts), or calls a hand-written fallback (`shim_fallback_<symbol>`) where an
error code is not safe, e.g. for functions that return a pointer or must
report zero devices. With --no-load, the real library is never loaded (e.g.
when it is built for another C++ standard library's ABI).

Outputs:
  <out>.S        the trampolines (x86_64 System V)
  <out>.c        the loader
  <out>.lds      the linker version script (symbol versions of the real
                 library, or one unversioned node)

Symbols come from GNU version scripts (--map, keeping their version nodes and
explicit C names), C headers (--header with --export-macro: every function
declared with that macro) and --symbol (e.g. mangled C++ names).
"""

import argparse
import re

_MAP_NODE = re.compile(r"^\s*([A-Za-z0-9_.]+)?\s*\{")
_MAP_END = re.compile(r"^\s*\}\s*([A-Za-z0-9_.]+)?\s*;")
_MAP_SYMBOL = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*;")


def parse_map(path):
    """Returns [(node, parent, [symbols])] of a GNU version script."""
    nodes = []
    node = None
    symbols = []
    scope = "global"
    depth = 0
    with open(path) as f:
        for line in f:
            line = line.split("#")[0]
            if depth == 0:
                match = _MAP_NODE.match(line)
                if match:
                    node, symbols, scope, depth = match.group(1), [], "global", 1
                continue
            if "{" in line:  # extern "C++" { ... }: mangled patterns, skipped.
                depth += 1
                continue
            if depth > 1:
                if "}" in line:
                    depth -= 1
                continue
            match = _MAP_END.match(line)
            if match:
                nodes.append((node, match.group(1), symbols))
                depth = 0
                continue
            # A scope label, possibly followed by a symbol on the same line.
            label = re.match(r"^\s*(global|local)\s*:", line)
            if label:
                scope = label.group(1)
                line = line[label.end():]
            match = _MAP_SYMBOL.match(line)
            if match and scope == "global":
                symbols.append(match.group(1))
    return nodes


def parse_headers(paths, macro):
    """Returns the functions declared with `macro` in C headers."""
    declaration = re.compile(r"\b" + re.escape(macro) + r"\b([^;{}()]*?)\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", re.S)
    symbols = []
    for path in paths:
        with open(path, encoding = "utf-8", errors = "replace") as f:
            text = f.read()
        text = re.sub(r"/\*.*?\*/", " ", text, flags = re.S)
        text = re.sub(r"//[^\n]*", " ", text)
        text = re.sub(r"^\s*#\s*define\b(?:[^\n]*\\\n)*[^\n]*", " ", text, flags = re.M)
        for match in declaration.finditer(text):
            symbols.append(match.group(2))
    return symbols


_ASM_HEADER = """\
// Generated by gen_shim.py: trampolines of {soname}.
    .text
"""

_ASM_SYMBOL = """\
    .globl {name}
    .type {name}, @function
    .p2align 4
{name}:
    jmp *shim_ptrs+{offset}(%rip)
    .size {name}, .-{name}
    .p2align 4
shim_lazy_{index}:
    movl ${index}, %r11d
    jmp shim_lazy
"""

# Saves the argument registers (and %rax, the vector register count of a
# variadic call), resolves the symbol in %r11d and tail-calls it.
_ASM_FOOTER = """\
    .p2align 4
shim_lazy:
    pushq %rdi
    pushq %rsi
    pushq %rdx
    pushq %rcx
    pushq %r8
    pushq %r9
    pushq %rax
    subq $128, %rsp
    movdqu %xmm0, 0(%rsp)
    movdqu %xmm1, 16(%rsp)
    movdqu %xmm2, 32(%rsp)
    movdqu %xmm3, 48(%rsp)
    movdqu %xmm4, 64(%rsp)
    movdqu %xmm5, 80(%rsp)
    movdqu %xmm6, 96(%rsp)
    movdqu %xmm7, 112(%rsp)
    movl %r11d, %edi
    call shim_resolve@PLT
    movq %rax, %r11
    movdqu 0(%rsp), %xmm0
    movdqu 16(%rsp), %xmm1
    movdqu 32(%rsp), %xmm2
    movdqu 48(%rsp), %xmm3
    movdqu 64(%rsp), %xmm4
    movdqu 80(%rsp), %xmm5
    movdqu 96(%rsp), %xmm6
    movdqu 112(%rsp), %xmm7
    addq $128, %rsp
    popq %rax
    popq %r9
    popq %r8
    popq %rcx
    popq %rdx
    popq %rsi
    popq %rdi
    jmp *%r11

    .data
    .p2align 3
    .globl shim_ptrs
    .hidden shim_ptrs
shim_ptrs:
{pointers}
    .section .note.GNU-stack,"",@progbits
"""

_C_SOURCE = """\
// Generated by gen_shim.py: loader of {soname}.
#define _GNU_SOURCE  // dladdr()
#include <dlfcn.h>
#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

extern void* shim_ptrs[];

static const char* const shim_names[] = {{
{names}
}};

{fallback_declarations}

static void* const shim_fallbacks[] = {{
{fallbacks}
}};

static void* shim_handle;
static pthread_once_t shim_once = PTHREAD_ONCE_INIT;

// Loads the real library by absolute path, never by SONAME, which would
// find this shim (already loaded under that SONAME) instead.
static void shim_open(void) {{
  if ({no_load}) return;
  Dl_info self;
  dladdr((void*)shim_open, &self);
  const char* roots[] = {{getenv("ROCM_PATH"), getenv("HIP_PATH"), "/opt/rocm"}};
  char path[4096];
  for (size_t i = 0; i < sizeof(roots) / sizeof(roots[0]) && !shim_handle; ++i) {{
    if (roots[i] == NULL || roots[i][0] == '\\0') continue;
    for (const char* lib = "lib\\0lib64\\0"; *lib && !shim_handle; lib += strlen(lib) + 1) {{
      snprintf(path, sizeof(path), "%s/%s/%s", roots[i], lib, "{soname}");
      shim_handle = dlopen(path, RTLD_NOW | RTLD_LOCAL);
    }}
  }}
  // Then LD_LIBRARY_PATH and the system directories, skipping this shim.
  const char* ld_library_path = getenv("LD_LIBRARY_PATH");
  char dirs[8192];
  snprintf(dirs, sizeof(dirs), "%s:/usr/lib/x86_64-linux-gnu:/usr/lib64:/usr/lib", ld_library_path ? ld_library_path : "");
  for (char* save = NULL, *dir = strtok_r(dirs, ":", &save); dir && !shim_handle; dir = strtok_r(NULL, ":", &save)) {{
    snprintf(path, sizeof(path), "%s/%s", dir, "{soname}");
    char resolved[4096];
    if (realpath(path, resolved) == NULL) continue;
    char self_resolved[4096];
    if (self.dli_fname && realpath(self.dli_fname, self_resolved) && strcmp(resolved, self_resolved) == 0) continue;
    shim_handle = dlopen(resolved, RTLD_NOW | RTLD_LOCAL);
  }}
}}

// Without the real library, every function without a fallback does this.
{unavailable}

void* shim_resolve(unsigned index) {{
  pthread_once(&shim_once, shim_open);
  void* target = shim_handle ? dlsym(shim_handle, shim_names[index]) : NULL;
  if (target == NULL) target = shim_fallbacks[index] ? shim_fallbacks[index] : (void*)shim_unavailable;
  __atomic_store_n(&shim_ptrs[index], target, __ATOMIC_RELEASE);
  return target;
}}

// Whether the real library was found (for the fallbacks).
int shim_{prefix}_available(void) {{
  pthread_once(&shim_once, shim_open);
  return shim_handle != NULL;
}}
"""


def main():
    parser = argparse.ArgumentParser(description = __doc__)
    parser.add_argument("--soname", required = True)
    parser.add_argument("--prefix", required = True, help = "Name of shim_<prefix>_available().")
    parser.add_argument("--error", help = "Return value of unavailable functions.")
    parser.add_argument("--abort", action = "store_true", help = "Unavailable functions abort instead (e.g. C++ functions returning objects).")
    parser.add_argument("--no-load", action = "store_true", help = "Never load the real library (e.g. built for another C++ ABI).")
    parser.add_argument("--map", action = "append", default = [])
    parser.add_argument("--header", action = "append", default = [])
    parser.add_argument("--export-macro")
    parser.add_argument("--symbol", action = "append", default = [], help = "Another exported symbol.")
    parser.add_argument("--fallback", action = "append", default = [], help = "Symbols with a shim_fallback_<symbol>.")
    parser.add_argument("--exclude", action = "append", default = [])
    parser.add_argument("--out", required = True)
    args = parser.parse_args()
    if not args.abort and args.error is None:
        parser.error("--error or --abort is required")

    nodes = []
    for path in args.map:
        nodes.extend(parse_map(path))
    if args.header or args.symbol:
        nodes.append((None, None, (parse_headers(args.header, args.export_macro) if args.header else []) + args.symbol))

    # Each symbol once, in its first (oldest) version node.
    seen = set(args.exclude)
    symbols = []
    for i, (node, parent, names) in enumerate(nodes):
        kept = []
        for name in names:
            if name not in seen:
                seen.add(name)
                kept.append(name)
        nodes[i] = (node, parent, kept)
        symbols.extend(kept)

    with open(args.out + ".S", "w") as f:
        f.write(_ASM_HEADER.format(soname = args.soname))
        for index, name in enumerate(symbols):
            f.write(_ASM_SYMBOL.format(name = name, index = index, offset = 8 * index))
        f.write(_ASM_FOOTER.format(pointers = "\n".join("    .quad shim_lazy_{}".format(i) for i in range(len(symbols)))))

    fallbacks = set(args.fallback)
    with open(args.out + ".c", "w") as f:
        f.write(_C_SOURCE.format(
            soname = args.soname,
            prefix = args.prefix,
            no_load = int(args.no_load),
            unavailable = (
                'static void shim_unavailable(void) {{ fprintf(stderr, "{}: not available\\n"); abort(); }}'.format(args.soname)
                if args.abort else
                "static long shim_unavailable(void) {{ return {}; }}".format(args.error)
            ),
            names = "\n".join('    "{}",'.format(name) for name in symbols),
            fallback_declarations = "\n".join("void shim_fallback_{}(void);".format(name) for name in symbols if name in fallbacks),
            fallbacks = "\n".join("    (void*)shim_fallback_{},".format(name) if name in fallbacks else "    0," for name in symbols),
        ))

    with open(args.out + ".lds", "w") as f:
        for node, parent, names in nodes:
            if not names and node:
                names = []
            f.write("{} {{\nglobal:\n".format(node or ""))
            for name in names:
                f.write("    {};\n".format(name))
            f.write("local:\n    *;\n}}{};\n\n".format(" " + parent if parent else ""))


if __name__ == "__main__":
    main()
